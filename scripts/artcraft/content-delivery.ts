import { lstat, readFile, readdir } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { checkContentAudit, contentRoot } from "./content-audit.ts";
import { contentNoticeFiles } from "./content-notices.ts";
import { digest, relativePath } from "./content-schema.ts";
import { sha256 } from "./evidence-bytes.ts";
import { adoptedNoticeFiles } from "./content-adoption.ts";

export const noticeRoot = fileURLToPath(
  new URL("../../tooling/artcraft/notice-supplement/", import.meta.url),
);

// Independently adopt the exact 130-file supplement; regenerating its own index cannot weaken it.
export const noticeIndexSha256 = "1c831022e11e86fd04ee67090f1291b615d4f10e9ffe13ec3908c5ea8b1aa906";

const indexSchema = z.object({
  schemaVersion: z.literal(1),
  deployable: z.literal(false),
  sourceAuditIndexSha256: digest,
  files: z.array(
    z.object({ path: relativePath, bytes: z.number().int().nonnegative(), sha256: digest }),
  ),
});

/** Refuse links at any component, not just the final notice/source filename. */
export async function readAcquisitionFile(root: string, path: string) {
  relativePath.parse(path);
  let current = root;
  const parts = path.split("/");

  for (const [index, part] of ["", ...parts].entries()) {
    current = part ? join(current, part) : current;
    const stat = await lstat(current);

    if (stat.isSymbolicLink() || (index === parts.length ? !stat.isFile() : !stat.isDirectory()))
      throw new Error(`Acquisition requires regular files/directories, not links: ${path}`);
  }

  return readFile(current);
}

/** Verify the frozen supplement and its entire evidence input offline before acquisition starts. */
export async function contentDeliveryFiles(root = noticeRoot) {
  const indexBytes = await readAcquisitionFile(root, "index.json");

  if (sha256(indexBytes) !== noticeIndexSha256)
    throw new Error("Notice delivery index pin mismatch");
  const index = indexSchema.parse(JSON.parse(indexBytes.toString()));

  if (sha256(await readFile(join(contentRoot, "index.json"))) !== index.sourceAuditIndexSha256)
    throw new Error("Notice delivery source audit pin mismatch");
  const { audit, discovered, files: evidenceFiles } = await checkContentAudit();
  const generated = await contentNoticeFiles();
  const files = new Map<string, Buffer>();
  const seen = new Set<string>();

  for (const record of index.files) {
    if (seen.has(record.path)) throw new Error("Duplicate notice delivery path");
    seen.add(record.path);
    const body = await readAcquisitionFile(root, `files/${record.path}`);

    if (
      body.length !== record.bytes ||
      sha256(body) !== record.sha256 ||
      !body.equals(generated.get(record.path) ?? Buffer.alloc(0))
    )
      throw new Error(`Notice delivery checksum/evidence mismatch: ${record.path}`);
    files.set(`legal/content/${record.path}`, body);
  }

  if (seen.size !== generated.size) throw new Error("Notice delivery missing generated bytes");

  async function checkTree(relative = "") {
    for (const name of await readdir(join(root, "files", relative))) {
      const path = relative ? `${relative}/${name}` : name;
      const stat = await lstat(join(root, "files", path));

      if (stat.isSymbolicLink()) throw new Error("Notice delivery link rejected");

      if (stat.isDirectory()) await checkTree(path);
      else if (!stat.isFile() || !seen.has(path))
        throw new Error(`Unaccounted notice delivery file: ${path}`);
    }
  }

  await checkTree();

  const manifest = z
    .object({
      entries: z.array(z.object({ path: relativePath, member: z.string(), source: z.string() })),
    })
    .parse(JSON.parse(files.get("legal/content/notice-manifest.json")!.toString()));

  const evidencePaths = new Map(
    manifest.entries.map((entry) => [
      entry.path
        .split("/")
        .at(-1)!
        .replace(/\.txt$/, ""),
      `content/${entry.path}`,
    ]),
  );

  // The original supplement does not include separate attribution/NOTICE provenance witnesses.
  // Deliver those whole files too, without editing or relabelling them as permission grants.
  const sourceNotices = audit.evidence.filter((evidence) =>
    /ATTRIBUTION|NOTICE|COPYRIGHT|AUTHORS|ACKNOWLEDG/i.test(evidence.member),
  );

  for (const evidence of sourceNotices) {
    const path = `content-source-notices/${evidence.id}.txt`;
    files.set(`legal/${path}`, evidenceFiles.get(evidence.id)!);

    if (!evidencePaths.has(evidence.id)) evidencePaths.set(evidence.id, path);
  }

  const correspondenceRoot = fileURLToPath(
    new URL("../../tooling/artcraft/pdfcraft-data-decision/", import.meta.url),
  );

  for (const [source, path, expected] of [
    [
      "correspondence.json",
      "legal/DATA-CORRESPONDENCE.json",
      "075b759c3653d0730973653dea4c62803a4835c6a7e84f6a7e8f5ba3cd9afff0",
    ],
    [
      "compiled-tables.json",
      "legal/PDFCRAFT-DATA-CORRESPONDENCE.json",
      "31aedc3d71c43cad4681c2108f8fee15e86f899e003a1fc6616ac4fa8b520581",
    ],
  ]) {
    const body = await readAcquisitionFile(correspondenceRoot, source!);

    if (sha256(body) !== expected)
      throw new Error(`Mechanical correspondence pin mismatch: ${source}`);
    files.set(path!, body);
  }

  for (const [path, body] of await adoptedNoticeFiles()) files.set(path, body);

  const coverage = {
    schemaVersion: 1,
    deployable: false,
    fullNoticeAuditComplete: false,
    compilerGeneratedNoticeAuditComplete: false,
    protectedMarksCleared: false,
    legalOpinion: false,
    scope:
      "Complete retained multi-editor supplement; conservative entries do not assert all components ship in each editor.",
    materials: audit.materials.map((material) => ({
      ...material,
      evidence: material.evidence.map((id) => ({
        id,
        notice:
          evidencePaths.get(id) ??
          (audit.evidence.find((file) => file.id === id)?.member === "embedded-font-copyrights"
            ? "content/EMBEDDED-FONT-COPYRIGHTS.txt"
            : null),
        retainedEvidence: audit.evidence.find((file) => file.id === id)!,
      })),
    })),
    supplementalCorrespondence: {
      declaredVersionsAndIdenticalSources: "DATA-CORRESPONDENCE.json",
      pdfcraftNumericTables: "PDFCRAFT-DATA-CORRESPONDENCE.json",
      adoptedExistingData: "adopted-data/index.json",
      note: "The frozen audit is historical. Later positive AFM/AGL/PDFium permission/correspondence evidence is now composed into acquired notices. Existing numeric/mapping behavior is preserved; no legal opinion or full audit clearance is asserted. See adopted-data/ADOPTION.md.",
    },
    unresolved: audit.unresolved,
  };

  files.set("legal/content-coverage.json", Buffer.from(`${JSON.stringify(coverage, null, 2)}\n`));

  const lines = [
    "# Local ArtCraft notice index",
    "",
    "Technical redistribution evidence only — not legal advice, clearance, or deployment approval. All clearance/deployability flags remain false. This directory is local acquisition output, not runtime publication or asset enablement.",
    "",
    "## Start here",
    "",
    "- [Content notice manifest](content/notice-manifest.json): exact source/member and hashes for the preserved supplement.",
    "- [Content coverage and unresolved actions](content-coverage.json): all discovered dispositions; notice paths are relative to this legal directory. A null notice means retained audit evidence, not a silently satisfied obligation.",
    "- [Observed font copyrights](content/EMBEDDED-FONT-COPYRIGHTS.txt).",
    "- [Adopted existing-data notices](adopted-data/ADOPTION.md), [exact file/source/hash catalog](adopted-data/index.json), [AFM-specific companion permission](adopted-data/adobe-core14/readme.txt), [AGL grant](adopted-data/adobe-agl/glyphlist.txt), and [PDFium licence](adopted-data/pdfium/LICENSE). All original inputs remain unchanged; current mapping behavior is preserved.",
    "- [Source-version/byte-identity answers](DATA-CORRESPONDENCE.json) and [positive PdfCraft numeric-table observations](PDFCRAFT-DATA-CORRESPONDENCE.json). These supplement the frozen audit without clearing rights or asserting unique source origin.",
    "- [Dependency notices](DEPENDENCY-NOTICES.md) and [matching Symphonia sources](SYMPHONIA-SOURCES.md).",
    "- Original upstream LICENSE/NOTICE/attribution files remain alongside this index, not replaced by it. The enclosing artifact manifest hashes every delivered file.",
    "",
    "The complete frozen supplement is copied conservatively into every acquisition, including modified Deck. Entries for other editors/unlinked compiler source are not assertions that those materials ship here. Source correspondence and Adobe-derived data rights remain bounded by the coverage record; negative byte search never proves absence.",
    "",
    "The preserved content/CONTENT-NOTICES.md and notice-manifest.json are the exact earlier generated snapshot: their 'not yet wired' wording describes that historical snapshot. This index and the enclosing artifact manifest record local delivery integration only. Runtime delivery, marks, rights/provenance and real backend/SDK/WASM acceptance remain separate gates.",
    "",
    "## Preserved source notices",
    "",
    ...manifest.entries.map(
      (entry) =>
        `- [${entry.path}](content/${entry.path}) — ${JSON.stringify(entry.member)}; source ${JSON.stringify(entry.source)}`,
    ),
    "",
    "## Additional whole-file attribution/copyright witnesses",
    "",
    ...sourceNotices.map(
      (evidence) =>
        `- [${evidence.id}](content-source-notices/${evidence.id}.txt) — ${JSON.stringify(evidence.member)}; source ${JSON.stringify(evidence.source)}`,
    ),
    "",
  ];

  files.set("legal/NOTICE-INDEX.md", Buffer.from(lines.join("\n")));
  files.set("legal/content-supplement-index.json", indexBytes);

  return { files, discovered, indexSha256: noticeIndexSha256 };
}

export function assertAuditedAsset(
  discovered: Awaited<ReturnType<typeof checkContentAudit>>["discovered"],
  artifact: string,
  path: string,
  body: Buffer,
) {
  const record = discovered.assets.find(
    (asset) => asset.artifact === artifact && asset.path === path,
  );

  if (!record || record.bytes !== body.length || record.sha256 !== sha256(body))
    throw new Error(`Acquisition payload differs from notice audit: ${artifact}:${path}`);
}

if (import.meta.main) {
  const delivery = await contentDeliveryFiles();
  console.log(
    `Verified ${delivery.files.size} local notice delivery files; deployable:false, runtimePublication:false`,
  );
}
