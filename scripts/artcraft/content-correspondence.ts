import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { checkContentAudit } from "./content-audit.ts";
import { readAcquisitionFile } from "./content-delivery.ts";
import { digest, relativePath } from "./content-schema.ts";
import { sha256 } from "./evidence-bytes.ts";

export const pdfDecisionRoot = fileURLToPath(
  new URL("../../tooling/artcraft/pdfcraft-data-decision/", import.meta.url),
);

const pdfIndexSha256 = "cd00b3968c8f319085cbf6998f845bd68e28666e04945fb0d4713be48836928e";

const sourceIndex = z.object({
  sourceArchiveSha256: digest,
  commit: z.literal("7d78f3e14474b978be014715e0cc64895d77025a"),
  deployable: z.literal(false),
  files: z.array(
    z.object({ member: relativePath, path: relativePath, bytes: z.number(), sha256: digest }),
  ),
});

/** Answer retained-byte identity, declared-version and table-shape questions, not source rights. */
export async function contentCorrespondence(root = pdfDecisionRoot) {
  const { audit, discovered, files } = await checkContentAudit();

  const versionDeclarations = audit.evidence.flatMap((evidence) => {
    const body = files.get(evidence.id)!.toString();

    const expressions = [
      /pub const UNICODE_VERSION[^=]*=\s*\(\s*\d+,\s*\d+,\s*\d+\s*\)/g,
      /\/\/ Unicode version: [0-9.]+/g,
      /generated by generate\.sh from Unicode CLDR [0-9.]+/g,
      /generated with CLDR version [^,\n]+, ICU version [^,\n]+, and\r?\n[^\n]+/g,
    ];

    return expressions.flatMap((expression) =>
      [...body.matchAll(expression)].map((match) => ({
        evidence: evidence.id,
        member: evidence.member,
        source: evidence.source,
        sha256: evidence.sha256,
        line: body.slice(0, match.index).split("\n").length,
        declaration: match[0],
        disposition:
          "Source version explicitly declared; independent generation and linked-output attribution remain unverified.",
      })),
    );
  });

  const identities = new Map<string, typeof discovered.references>();

  for (const reference of discovered.references) {
    const key = `${reference.bytes}:${reference.sha256}`;
    const group = identities.get(key) ?? [];
    group.push(reference);
    identities.set(key, group);
  }

  const identicalSourceGroups = [...identities.values()].flatMap((group) =>
    group.length > 1 && group.some((ref) => ref.matches.length)
      ? [
          {
            bytes: group[0]!.bytes,
            sha256: group[0]!.sha256,
            sources: group.map((ref) => ({ id: ref.id, member: ref.member, matches: ref.matches })),
            disposition:
              "Byte identity and recorded positive output observations resolved; these bytes cannot uniquely distinguish the listed source origins.",
          },
        ]
      : [],
  );

  const indexBytes = await readAcquisitionFile(root, "index.json");

  if (sha256(indexBytes) !== pdfIndexSha256)
    throw new Error("PdfCraft decision source index pin mismatch");
  const index = sourceIndex.parse(JSON.parse(indexBytes.toString()));
  const pdfFiles = new Map<string, Buffer>();

  for (const file of index.files) {
    const body = await readAcquisitionFile(root, file.path);

    if (body.length !== file.bytes || sha256(body) !== file.sha256)
      throw new Error(`PdfCraft decision source bytes changed: ${file.member}`);
    pdfFiles.set(file.member, body);
  }

  for (const member of ["crates/fonts/src/std14_metrics.rs", "crates/fonts/src/encodings.rs"]) {
    const reference = discovered.references.find((ref) => ref.id === `pdfcraft-source:${member}`)!;

    if (sha256(pdfFiles.get(member)!) !== reference.sha256)
      throw new Error("PdfCraft data differs from existing audit");

    if (
      audit.materials.find((material) => material.id === `source:${reference.id}`)?.disposition !==
      "unresolved"
    )
      throw new Error("PdfCraft rights disposition unexpectedly cleared");
  }

  const widths = z
    .array(z.array(z.number().int().nonnegative().max(65535)).length(256))
    .length(14)
    .parse(parsePdfFontTable(pdfFiles.get("crates/fonts/src/std14_metrics.rs")!, "WIDTHS"));

  const encodings = Object.fromEntries(
    ["WIN_ANSI", "MAC_ROMAN", "STANDARD"].map((name) => [
      name,
      z
        .array(z.number().int().nonnegative().max(0x10ffff))
        .length(256)
        .parse(parsePdfFontTable(pdfFiles.get("crates/fonts/src/encodings.rs")!, name)),
    ]),
  );

  const std14 = pdfFiles.get("crates/fonts/src/std14.rs")!.toString();
  const pdf = pdfFiles.get("crates/fonts/src/pdf.rs")!.toString();

  if (
    !std14.includes("crate::std14_metrics::WIDTHS[self as usize][code as usize]") ||
    !pdf.includes("crate::encodings::NAMES.binary_search_by")
  )
    throw new Error("PdfCraft data consumers changed");

  return {
    schemaVersion: 1,
    deployable: false,
    fullNoticeAuditComplete: false,
    compilerGeneratedNoticeAuditComplete: false,
    legalOpinion: false,
    method:
      "Offline facts derived from previously retained evidence; source declarations are not independently reproduced upstream data or binary link attestations.",
    versionDeclarations,
    identicalSourceGroups,
    pdfcraft: {
      sourceArchiveSha256: index.sourceArchiveSha256,
      commit: index.commit,
      files: index.files,
      fontFaces: widths.length,
      codesPerFace: widths[0]!.length,
      encodingLengths: Object.fromEntries(
        Object.entries(encodings).map(([name, values]) => [name, values.length]),
      ),
      semanticChecks: {
        winAnsiA0IsSpace: encodings.WIN_ANSI![0xa0] === 32,
        winAnsiADIsHyphen: encodings.WIN_ANSI![0xad] === 45,
        macRomanCAIsSpace: encodings.MAC_ROMAN![0xca] === 32,
      },
      disposition:
        "unresolved-source-rights; concrete data shape and consumers established, not removed by an unsuccessful whole-source byte search",
    },
  };
}

export function parsePdfFontTable(body: Buffer, name: string) {
  const fontCodes = z.array(z.number().int().nonnegative().max(0x10ffff)).max(256);
  const fontTables = z.union([fontCodes, z.array(fontCodes).max(14)]);
  const text = body.toString().replace(/\/\/[^\n]*/g, "");
  const literal = text.match(new RegExp(`static ${name}[^=]*=\\s*(\\[[\\s\\S]*?\\n\\]);`))?.[1];

  if (!literal) throw new Error(`PdfCraft data table changed: ${name}`);

  return fontTables.parse(JSON.parse(literal.replace(/,\s*\]/g, "]")));
}

if (import.meta.main) {
  const [, , output] = process.argv;
  const bytes = Buffer.from(`${JSON.stringify(await contentCorrespondence(), null, 2)}\n`);

  if (output) await writeFile(output, bytes, { flag: "wx" });
  else {
    const retained = await readFile(join(pdfDecisionRoot, "correspondence.json"));

    if (!retained.equals(bytes)) throw new Error("Retained mechanical correspondence changed");
    console.log(
      "Verified retained source versions, byte-identity ambiguities and PdfCraft data shapes; rights/deployment gates remain false.",
    );
  }
}
