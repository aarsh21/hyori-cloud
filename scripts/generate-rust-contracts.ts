function fail(location: string, message: string): never {
  throw new Error(`${location}: ${message}`);
}

function compare(left: string, right: string) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function identifier(name: string, location: string) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) || forbiddenNames.has(name)) {
    fail(location, `unsafe or reserved schema identifier ${JSON.stringify(name)}`);
  }
}

function namespace(name: string, location: string) {
  const parts = name.split(".");

  if (parts.some((part) => !/^[A-Za-z][A-Za-z0-9]*$/.test(part) || forbiddenNames.has(part))) {
    fail(location, `unsafe operation namespace ${JSON.stringify(name)}`);
  }
}

function canonical(value: JsonValue): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;

  if (value !== null && Object(value) === value) {
    return `{${Object.entries(value)
      .sort(([a], [b]) => compare(a, b))
      .map(([key, child]) => `${JSON.stringify(key)}:${canonical(child)}`)
      .join(",")}}`;
  }

  return JSON.stringify(value);
}

function canonicalSchema(schema: JsonSchema): string {
  const normalized: Record<string, JsonValue> = {};

  for (const [key, value] of Object.entries(schema)) {
    if (!annotations.has(key) && value !== undefined) normalized[key] = z.json().parse(value);
  }

  // Schemars root schemas can carry titles/descriptions absent from the same type's nested definition.
  if (schema.properties)
    normalized.properties = Object.fromEntries(
      Object.entries(schema.properties).map(([key, child]) => [key, canonicalSchema(child)]),
    );

  if (schema.items) normalized.items = canonicalSchema(schema.items);

  if (schema.additionalProperties && schema.additionalProperties !== true)
    normalized.additionalProperties = canonicalSchema(schema.additionalProperties);

  for (const key of ["allOf", "anyOf", "oneOf"] as const) {
    if (schema[key]) normalized[key] = schema[key].map(canonicalSchema);
  }

  if (schema.required) normalized.required = [...schema.required].sort(compare);

  return canonical(normalized);
}

function refName(reference: string, location: string) {
  if (!/^#\/\$defs\/([^/]+)$/.test(reference)) {
    fail(location, `unsupported reference ${JSON.stringify(reference)}; expected #/$defs/Name`);
  }

  const name = reference.slice("#/$defs/".length).replaceAll("~1", "/").replaceAll("~0", "~");
  identifier(name, location);

  return name;
}

function children(schema: JsonSchema): [string, JsonSchema][] {
  return [
    ...Object.entries(schema.properties ?? {}).map(([key, value]): [string, JsonSchema] => [
      `properties.${key}`,
      value,
    ]),
    ...Object.entries(schema.$defs ?? {}).map(([key, value]): [string, JsonSchema] => [
      `$defs.${key}`,
      value,
    ]),
    ...(schema.items ? [["items", schema.items] satisfies [string, JsonSchema]] : []),
    ...(schema.additionalProperties && schema.additionalProperties !== true
      ? [["additionalProperties", schema.additionalProperties] satisfies [string, JsonSchema]]
      : []),
    ...(schema.anyOf ?? []).map((value, index): [string, JsonSchema] => [`anyOf.${index}`, value]),
    ...(schema.oneOf ?? []).map((value, index): [string, JsonSchema] => [`oneOf.${index}`, value]),
    ...(schema.allOf ?? []).map((value, index): [string, JsonSchema] => [`allOf.${index}`, value]),
  ];
}

function collectSchemas(manifest: RustContractManifest) {
  const schemas = new Map<string, JsonSchema>();

  const register = (name: string, schema: JsonSchema, location: string) => {
    identifier(name, location);
    // Definitions are document-local in JSON Schema. A single generated namespace is safe only when every reuse agrees.
    const { $defs: _definitions, ...definition } = schema;
    const previous = schemas.get(name);

    if (previous && canonicalSchema(previous) !== canonicalSchema(definition)) {
      fail(location, `conflicting schema definition ${name}`);
    }

    schemas.set(name, definition);
  };

  const visit = (schema: JsonSchema, location: string) => {
    for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
      register(name, definition, `${location}.$defs.${name}`);
    }

    for (const [key, child] of children(schema)) visit(child, `${location}.${key}`);
  };

  for (const [name, schema] of Object.entries(manifest.schemas))
    register(name, schema, `schemas.${name}`);

  for (const [name, schema] of Object.entries(manifest.schemas)) visit(schema, `schemas.${name}`);

  return schemas;
}

function sortedSchemas(schemas: Map<string, JsonSchema>) {
  const result: string[] = [];
  const complete = new Set<string>();
  const active: string[] = [];

  const visit = (name: string) => {
    if (complete.has(name)) return;

    if (active.includes(name))
      fail(`schemas.${name}`, `cyclic schema references: ${[...active, name].join(" -> ")}`);
    const schema = schemas.get(name);

    if (!schema) fail(`schemas.${active.at(-1) ?? name}`, `dangling reference ${name}`);
    active.push(name);
    const refs = new Set<string>();

    const findRefs = (node: JsonSchema, location: string) => {
      if (node.$ref) refs.add(refName(node.$ref, location));

      for (const [key, child] of children(node)) {
        if (!key.startsWith("$defs.")) findRefs(child, `${location}.${key}`);
      }
    };

    findRefs(schema, `schemas.${name}`);

    for (const dependency of [...refs].sort(compare)) visit(dependency);
    active.pop();
    complete.add(name);
    result.push(name);
  };

  for (const name of [...schemas.keys()].sort(compare)) visit(name);

  return result;
}

function checkKeywords(schema: JsonSchema, type: string | undefined, location: string) {
  for (const [expected, keywords] of [
    ["string", stringKeywords],
    ["number", numberKeywords],
    ["array", arrayKeywords],
    ["object", objectKeywords],
  ] as const) {
    if (type === expected || (expected === "number" && type === "integer")) continue;

    for (const key of keywords) {
      if (Object.hasOwn(schema, key))
        fail(location, `${key} requires an explicit ${expected} type`);
    }
  }
}

function pipe(expression: string, filters: string[]) {
  return filters.length ? `${expression}.pipe(${filters.join(", ")})` : expression;
}

function literal(value: Primitive, location: string) {
  if (value === null) return "Schema.Null";

  if (
    z.number().safeParse(value).success &&
    !Number.isSafeInteger(value) &&
    Number.isInteger(value)
  ) {
    fail(location, "integer literal is outside JavaScript's safe integer range");
  }

  return `Schema.Literal(${JSON.stringify(value)})`;
}

function compile(schema: JsonSchema, location: string, name?: string): string {
  const structuralKeys = Object.keys(schema).filter((key) => !annotations.has(key));

  if (structuralKeys.length === 0) {
    if (name === "Unknown") return "Schema.Unknown";
    fail(
      location,
      'unconstrained schema requires the explicit name Unknown or "x-hyori-unknown": true',
    );
  }

  if (schema["x-hyori-unknown"] === true) {
    if (structuralKeys.length !== 1)
      fail(location, "explicit Unknown cannot have other constraints");

    return "Schema.Unknown";
  }

  if (schema["x-hyori-unknown"] === false) fail(location, 'unsupported "x-hyori-unknown": false');

  if (Array.isArray(schema.type)) {
    if (new Set(schema.type).size !== schema.type.length)
      fail(location, "duplicate type union member");

    // JSON Schema applies type-specific constraints only to members of that type.
    return `Schema.Union(${schema.type
      .map((type) => {
        const member = { ...schema, type };

        for (const [expected, keywords] of [
          ["string", stringKeywords],
          ["number", numberKeywords],
          ["array", arrayKeywords],
          ["object", objectKeywords],
        ] as const) {
          if (type !== expected && !(expected === "number" && type === "integer")) {
            for (const key of keywords) delete member[key];
          }
        }

        if (type === "null") delete member.format;

        return compile(member, location);
      })
      .join(", ")})`;
  }

  const type = schema.type;
  checkKeywords(schema, type, location);

  if (schema.format) {
    const supported =
      type === "string" || type === undefined
        ? ["date", "date-time"]
        : type === "integer"
          ? ["uint32", "uint64", "int32", "int64"]
          : type === "number"
            ? ["float", "double"]
            : [];

    if (!supported.includes(schema.format))
      fail(location, `unsupported format ${JSON.stringify(schema.format)} for ${type}`);
  }

  const components: string[] = [];

  if (schema.$ref) components.push(refName(schema.$ref, location));

  if (schema.anyOf)
    components.push(
      `Schema.Union(${schema.anyOf.map((child, index) => compile(child, `${location}.anyOf.${index}`)).join(", ")})`,
    );

  if (schema.oneOf)
    components.push(
      `exclusiveUnion(${schema.oneOf.map((child, index) => compile(child, `${location}.oneOf.${index}`)).join(", ")})`,
    );

  if (schema.allOf) {
    for (const [index, child] of schema.allOf.entries())
      components.push(compile(child, `${location}.allOf.${index}`));
  }

  if (schema.enum) {
    if (new Set(schema.enum.map((value) => JSON.stringify(value))).size !== schema.enum.length)
      fail(location, "duplicate enum member");
    components.push(
      `Schema.Union(${schema.enum.map((value) => literal(value, location)).join(", ")})`,
    );
  }

  if (Object.hasOwn(schema, "const")) components.push(literal(schema.const ?? null, location));
  const filters: string[] = [];
  let base: string | undefined;

  switch (type) {
    case "string":
      base = "Schema.String";

      if (schema.format)
        filters.push(
          `Schema.filter((value) => validDateFormat(value, ${JSON.stringify(schema.format)}))`,
        );

      // JSON Schema lengths count Unicode code points, unlike JavaScript's UTF-16 string.length.
      if (schema.minLength !== undefined)
        filters.push(`Schema.filter((value) => Array.from(value).length >= ${schema.minLength})`);

      if (schema.maxLength !== undefined)
        filters.push(`Schema.filter((value) => Array.from(value).length <= ${schema.maxLength})`);

      if (
        schema.minLength !== undefined &&
        schema.maxLength !== undefined &&
        schema.minLength > schema.maxLength
      )
        fail(location, "minLength exceeds maxLength");

      if (schema.pattern !== undefined) {
        try {
          new RegExp(schema.pattern, "u");
        } catch {
          fail(location, "invalid Unicode regular expression pattern");
        }

        filters.push(`Schema.pattern(new RegExp(${JSON.stringify(schema.pattern)}, "u"))`);
      }

      break;
    case "number":
    case "integer": {
      base = "Schema.Number";
      filters.push("Schema.finite()");

      if (type === "integer")
        filters.push(
          "Schema.int()",
          "Schema.between(Number.MIN_SAFE_INTEGER, Number.MAX_SAFE_INTEGER)",
        );

      if (schema.format === "uint32") filters.push("Schema.between(0, 4294967295)");

      if (schema.format === "uint64") filters.push("Schema.nonNegative()");

      if (schema.format === "int32") filters.push("Schema.between(-2147483648, 2147483647)");

      for (const [key, operation] of [
        ["minimum", "greaterThanOrEqualTo"],
        ["maximum", "lessThanOrEqualTo"],
        ["exclusiveMinimum", "greaterThan"],
        ["exclusiveMaximum", "lessThan"],
        ["multipleOf", "multipleOf"],
      ] as const) {
        const value = schema[key];

        if (value === undefined) continue;

        if (Math.abs(value) > Number.MAX_SAFE_INTEGER)
          fail(location, `${key} is outside JavaScript's safe numeric range`);
        filters.push(`Schema.${operation}(${value})`);
      }

      const lower = schema.minimum ?? schema.exclusiveMinimum;
      const upper = schema.maximum ?? schema.exclusiveMaximum;

      if (lower !== undefined && upper !== undefined && lower > upper)
        fail(location, "numeric lower bound exceeds upper bound");
      break;
    }

    case "boolean":
      base = "Schema.Boolean";
      break;
    case "null":
      base = "Schema.Null";
      break;
    case "array":
      if (!schema.items) fail(location, "array requires an explicit items schema");
      base = `Schema.Array(${compile(schema.items, `${location}.items`)})`;

      if (schema.minItems !== undefined) filters.push(`Schema.minItems(${schema.minItems})`);

      if (schema.maxItems !== undefined) filters.push(`Schema.maxItems(${schema.maxItems})`);

      if (
        schema.minItems !== undefined &&
        schema.maxItems !== undefined &&
        schema.minItems > schema.maxItems
      )
        fail(location, "minItems exceeds maxItems");

      if (schema.uniqueItems) fail(location, "uniqueItems is unsupported");
      break;
    case "object": {
      const properties = schema.properties ?? {};
      const required = new Set(schema.required ?? []);

      if (required.size !== (schema.required ?? []).length)
        fail(location, "duplicate required property");

      for (const key of required)
        if (!Object.hasOwn(properties, key))
          fail(location, `required property ${key} has no declaration`);

      if (schema.additionalProperties === true)
        fail(location, "additionalProperties requires an explicit value schema");

      if (schema.additionalProperties) {
        if (Object.keys(properties).length)
          fail(location, "mixed named properties and dictionary values are unsupported");

        base = pipe(
          `Schema.Record({ key: Schema.String, value: ${compile(schema.additionalProperties, `${location}.additionalProperties`)} })`,
          ["Schema.filter((value) => Object(value) === value && !Array.isArray(value))"],
        );
        break;
      }

      const fields = Object.entries(properties)
        .sort(([a], [b]) => compare(a, b))
        .map(([key, child]) => {
          if (prototypeNames.has(key))
            fail(location, `unsafe object property ${JSON.stringify(key)}`);
          const expression = compile(child, `${location}.properties.${key}`);

          // Optional JavaScript arguments may be undefined; JSON serialization omits those fields.
          return `${JSON.stringify(key)}: ${required.has(key) ? expression : `Schema.optional(${expression})`}`;
        });

      base = `Schema.Struct({${fields.length ? ` ${fields.join(", ")} ` : ""}})`;

      // Effect's empty Struct is the TypeScript {} type and also accepts primitives/arrays unless guarded.
      if (fields.length === 0)
        base = pipe(base, [
          `Schema.filter((value) => Object(value) === value && !Array.isArray(value)${schema.additionalProperties === false ? " && Object.keys(value).length === 0" : ""})`,
        ]);

      // Ordinary objects retain Effect's existing strip-on-decode behavior. An explicitly closed Rust object rejects extras.
      if (schema.additionalProperties === false)
        base += '.annotations({ parseOptions: { onExcessProperty: "error" } })';
      break;
    }

    case undefined:
      if (schema.format) {
        base = "Schema.Unknown";
        filters.push(
          `Schema.filter((value) => typeof value !== "string" || validDateFormat(value, ${JSON.stringify(schema.format)}))`,
        );
      }

      break;
    default:
      fail(location, `unsupported schema type ${JSON.stringify(type)}`);
  }

  if (base) components.push(pipe(base, filters));

  if (components.length === 0) fail(location, "schema has no supported type or composition");

  return components
    .slice(1)
    .reduce((expression, component) => `intersection(${expression}, ${component})`, components[0]!);
}

const dateFormatHelper = `
function validDateFormat(value: string, format: "date" | "date-time") {
  const match = /^(\\d{4})-(\\d{2})-(\\d{2})(.*)$/.exec(value);

  if (!match) return false;
  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = Number(match[3]);
  const leap = year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0);
  const days = [31, leap ? 29 : 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

  if (month < 1 || month > 12 || day < 1 || day > days[month - 1]!) return false;
  if (format === "date") return match[4] === "";
  const time = /^[Tt](\\d{2}):(\\d{2}):(\\d{2})(?:\\.\\d+)?([Zz]|([+-])(\\d{2}):(\\d{2}))$/.exec(match[4]!);

  if (!time) return false;
  const hour = Number(time[1]);
  const minute = Number(time[2]);
  const second = Number(time[3]);
  const offsetHour = Number(time[6] ?? 0);
  const offsetMinute = Number(time[7] ?? 0);

  if (hour > 23 || minute > 59 || second > 60 || offsetHour > 23 || offsetMinute > 59) return false;
  const offset = (offsetHour * 60 + offsetMinute) * (time[5] === "-" ? -1 : 1);
  const utcMinute = ((hour * 60 + minute - offset) % 1440 + 1440) % 1440;

  return second !== 60 || utcMinute === 1439;
}
`;

const intersectionHelper = `
// JSON Schema conjunction checks every member against the original value, not a previously stripped object.
function intersection<Left extends Schema.Schema.AnyNoContext, Right extends Schema.Schema.AnyNoContext>(left: Left, right: Right) {
  return Schema.declare<Schema.Schema.Type<Left> & Schema.Schema.Type<Right>>((value) => Schema.is(left)(value) && Schema.is(right)(value));
}
`;

const exclusiveUnionHelper = `
function exclusiveUnion<const Members extends readonly [Schema.Schema.AnyNoContext, ...Schema.Schema.AnyNoContext[]]>(...members: Members) {
  return Schema.declare<Schema.Schema.Type<Members[number]>>((value): value is Schema.Schema.Type<Members[number]> => {
    let matches = 0;

    for (const member of members) if (Schema.is(member)(value)) matches++;

    return matches === 1;
  });
}
`;

// The same validated Rust manifest also owns the JSON SDK codecs. No Effect machinery is needed
// to validate JSON; keep the existing Effect schemas/RPC exports for their existing consumers.
function compileWire(schema: JsonSchema, name?: string): string {
  if (schema["x-hyori-unknown"] || name === "Unknown") return "z.unknown()";

  if (Array.isArray(schema.type)) {
    return `z.union([${schema.type
      .map((type) => {
        const member = { ...schema, type };

        for (const [expected, keywords] of [
          ["string", stringKeywords],
          ["number", numberKeywords],
          ["array", arrayKeywords],
          ["object", objectKeywords],
        ] as const) {
          if (type !== expected && !(expected === "number" && type === "integer"))
            for (const key of keywords) delete member[key];
        }

        if (type === "null") delete member.format;

        return compileWire(member);
      })
      .join(", ")}])`;
  }

  const parts: string[] = [];

  if (schema.$ref) parts.push(refName(schema.$ref, "wire"));

  if (schema.anyOf)
    parts.push(`z.union([${schema.anyOf.map((child) => compileWire(child)).join(", ")}])`);

  if (schema.oneOf)
    parts.push(`exclusiveUnion(${schema.oneOf.map((child) => compileWire(child)).join(", ")})`);

  if (schema.allOf) parts.push(...schema.allOf.map((child) => compileWire(child)));

  if (schema.enum) parts.push(`z.literal(${JSON.stringify(schema.enum)})`);

  if (Object.hasOwn(schema, "const"))
    parts.push(`z.literal(${JSON.stringify(schema.const ?? null)})`);
  let base: string | undefined;
  const checks: string[] = [];

  switch (schema.type) {
    case "string":
      base = "z.string()";

      if (schema.format)
        checks.push(
          `z.refine((value) => validDateFormat(value, ${JSON.stringify(schema.format)}))`,
        );

      if (schema.minLength !== undefined)
        checks.push(`z.refine((value) => Array.from(value).length >= ${schema.minLength})`);

      if (schema.maxLength !== undefined)
        checks.push(`z.refine((value) => Array.from(value).length <= ${schema.maxLength})`);

      if (schema.pattern !== undefined)
        checks.push(`z.regex(new RegExp(${JSON.stringify(schema.pattern)}, "u"))`);
      break;
    case "integer":
    case "number":
      base = schema.type === "integer" ? "z.int()" : "z.number()";

      if (schema.format === "uint32") checks.push("z.gte(0)", "z.lte(4294967295)");

      if (schema.format === "uint64") checks.push("z.gte(0)");

      if (schema.format === "int32") checks.push("z.gte(-2147483648)", "z.lte(2147483647)");

      for (const [key, operation] of [
        ["minimum", "gte"],
        ["maximum", "lte"],
        ["exclusiveMinimum", "gt"],
        ["exclusiveMaximum", "lt"],
        ["multipleOf", "multipleOf"],
      ] as const) {
        if (schema[key] !== undefined) checks.push(`z.${operation}(${schema[key]})`);
      }

      break;
    case "boolean":
      base = "z.boolean()";
      break;
    case "null":
      base = "z.null()";
      break;
    case "array":
      base = `z.array(${compileWire(schema.items!)})`;

      if (schema.minItems !== undefined) checks.push(`z.minLength(${schema.minItems})`);

      if (schema.maxItems !== undefined) checks.push(`z.maxLength(${schema.maxItems})`);
      break;
    case "object": {
      if (schema.additionalProperties && schema.additionalProperties !== true) {
        base = `z.record(z.string(), ${compileWire(schema.additionalProperties)})`;
        break;
      }

      const required = new Set(schema.required ?? []);

      const fields = Object.entries(schema.properties ?? {})
        .sort(([a], [b]) => compare(a, b))
        .map(
          ([key, child]) =>
            `${JSON.stringify(key)}: ${required.has(key) ? compileWire(child) : `z.optional(${compileWire(child)})`}`,
        );

      base =
        fields.length === 0 && schema.additionalProperties !== false
          ? "z.custom<Record<string, unknown>>((value) => Object(value) === value && !Array.isArray(value))"
          : `z.${schema.additionalProperties === false ? "strictObject" : "object"}({ ${fields.join(", ")} })`;
      break;
    }

    case undefined:
      if (schema.format) {
        base = "z.unknown()";
        checks.push(
          `z.refine((value) => typeof value !== "string" || validDateFormat(value, ${JSON.stringify(schema.format)}))`,
        );
      }

      break;
  }

  if (base) parts.push(checks.length ? `${base}.check(${checks.join(", ")})` : base);

  return parts.slice(1).reduce((left, right) => `intersection(${left}, ${right})`, parts[0]!);
}

const wireCompositionHelpers = `
// Match the Effect compatibility surface: conjunction/exclusive union validate the original value.
function intersection<A, B>(left: z.ZodMiniType<A>, right: z.ZodMiniType<B>) {
  return z.custom<A & B>((value) => left.safeParse(value).success && right.safeParse(value).success);
}
function exclusiveUnion<const Members extends readonly z.ZodMiniType[]>(...members: Members) {
  return z.custom<z.infer<Members[number]>>((value) => members.filter((member) => member.safeParse(value).success).length === 1);
}
`;

export function generateRustContracts(manifest: RustContractManifest) {
  // Reject names before Zod's defensive record decoding can discard a prototype key.
  for (const name of Object.keys(manifest.schemas)) identifier(name, `schemas.${name}`);
  rejectDuplicateJsonKeys(JSON.stringify(manifest));

  const parsed = manifestParser.parse(manifest);
  const schemas = collectSchemas(parsed);
  const ordered = sortedSchemas(schemas);

  const declarations = ordered.map(
    (name) =>
      `export const ${name} = ${compile(schemas.get(name)!, `schemas.${name}`, name)};\n\nexport type ${name} = typeof ${name}.Type;`,
  );

  const sortedOperations = [...parsed.operations].sort((a, b) => compare(a.name, b.name));
  const names = new Set<string>();

  for (const operation of sortedOperations) {
    namespace(operation.name, `operations.${operation.name}`);

    if (names.has(operation.name)) fail("operations", `duplicate operation ${operation.name}`);
    names.add(operation.name);

    for (const schemaName of [operation.input, operation.output, operation.error]) {
      if (!schemas.has(schemaName))
        fail(`operations.${operation.name}`, `dangling schema ${schemaName}`);
    }

    for (const invalidation of operation.invalidates)
      namespace(invalidation, `operations.${operation.name}.invalidates`);

    if (new Set(operation.invalidates).size !== operation.invalidates.length)
      fail(`operations.${operation.name}`, "duplicate invalidation");
  }

  for (const name of names) {
    const segments = name.split(".");

    for (let index = 1; index < segments.length; index++) {
      const prefix = segments.slice(0, index).join(".");

      if (names.has(prefix))
        fail("operations", `namespace collision between ${prefix} and ${name}`);
    }
  }

  const imports = [
    ...new Set(
      sortedOperations.flatMap((operation) => [operation.input, operation.output, operation.error]),
    ),
  ].sort(compare);

  const descriptors = sortedOperations.map(
    (operation) =>
      `  {\n    rpc: Rpc.make(${JSON.stringify(operation.name)}, { payload: ${operation.input}, success: ${operation.output}, error: ${operation.error} }),\n    kind: ${JSON.stringify(operation.kind)},${operation.invalidates.length ? `\n    invalidates: ${JSON.stringify([...operation.invalidates].sort(compare))},` : ""}${operation.resetCache ? "\n    resetCache: true," : ""}\n  },`,
  );

  const clientDescriptors = sortedOperations.map(
    (operation) =>
      `  {\n    rpc: { _tag: ${JSON.stringify(operation.name)}, payloadSchema: ${operation.input}, successSchema: ${operation.output}, errorSchema: ${operation.error} },\n    kind: ${JSON.stringify(operation.kind)},${operation.invalidates.length ? `\n    invalidates: ${JSON.stringify([...operation.invalidates].sort(compare))},` : ""}${operation.resetCache ? "\n    resetCache: true," : ""}\n  },`,
  );

  const wireDeclarations = ordered.map(
    (name) =>
      `export const ${name}: z.ZodMiniType<Contract.${name}> = ${compileWire(schemas.get(name)!, name)};\nexport type ${name} = Contract.${name};`,
  );

  return {
    "schemas.ts": `${header}import { Schema } from "@hyori-cloud/lib/effect";\n${declarations.some((declaration) => declaration.includes("validDateFormat(")) ? dateFormatHelper : ""}${declarations.some((declaration) => declaration.includes("intersection(")) ? intersectionHelper : ""}${declarations.some((declaration) => declaration.includes("exclusiveUnion(")) ? exclusiveUnionHelper : ""}\n${declarations.join("\n\n")}\n`,
    "operations.ts": `${header}import { Rpc, RpcGroup } from "@hyori-cloud/lib/effect/rpc";\n${imports.length ? `import { ${imports.join(", ")} } from "./schemas";\n` : ""}\nexport const operations = [\n${descriptors.join("\n")}\n] as const;\n\nexport const ApiRpc = RpcGroup.make(...operations.map((operation) => operation.rpc));\n\nexport type Api = typeof ApiRpc;\n`,
    "client-operations.ts": `${header}${imports.length ? `import { ${imports.join(", ")} } from "./schemas";\n` : ""}\n// The JSON SDK needs codecs and policy metadata, not Effect RPC handlers or stream machinery.\nexport const operations = [\n${clientDescriptors.join("\n")}\n] as const;\n`,
    "wire-schemas.ts": `${header}import * as z from "@hyori-cloud/lib/json";\nimport type * as Contract from "./schemas";\n${wireDeclarations.some((declaration) => declaration.includes("validDateFormat(")) ? dateFormatHelper : ""}${wireDeclarations.some((declaration) => /(?:intersection|exclusiveUnion)\(/.test(declaration)) ? wireCompositionHelpers : ""}\n${wireDeclarations.join("\n\n")}\n`,
    "wire-operations.ts": `${header}${imports.length ? `import { ${imports.join(", ")} } from "./wire-schemas";\n` : ""}\nexport const operations = [\n${clientDescriptors.join("\n")}\n] as const;\n`,
  };
}

// JSON.parse silently overwrites duplicate object keys. Check the token stream before decoding the manifest.
function rejectDuplicateJsonKeys(source: string) {
  const tokens =
    source.match(/"(?:[^"\\]|\\.)*"|[{}[\]:,]|-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?|true|false|null/g) ??
    [];

  let index = 0;

  const visit = () => {
    const token = tokens[index++];

    if (token === "{") {
      const keys = new Set<string>();

      while (tokens[index] !== "}") {
        const key = z.string().parse(JSON.parse(tokens[index++] ?? ""));

        if (keys.has(key)) fail("manifest", `duplicate JSON key ${JSON.stringify(key)}`);

        if (["__proto__", "constructor", "prototype"].includes(key))
          fail("manifest", `unsafe object key ${JSON.stringify(key)}`);
        keys.add(key);
        index++;
        visit();

        if (tokens[index] !== ",") break;
        index++;
      }

      index++;
    } else if (token === "[") {
      while (tokens[index] !== "]") {
        visit();

        if (tokens[index] !== ",") break;
        index++;
      }

      index++;
    }
  };

  visit();
}

export function parseRustContractManifest(source: string) {
  // Validate JSON syntax first; the duplicate-key walk then only sees a valid grammar.
  const value = JSON.parse(source);
  rejectDuplicateJsonKeys(source);

  return manifestParser.parse(value);
}

const cliParser = z.strictObject({
  input: z.string().min(1),
  output: z.string().min(1),
  check: z.boolean(),
});

async function assertRegularFile(path: string) {
  const stat = await lstat(path).catch((cause: NodeJS.ErrnoException) => {
    if (cause.code === "ENOENT") return undefined;
    throw cause;
  });

  if (stat && (!stat.isFile() || stat.isSymbolicLink()))
    fail(path, "refusing to replace a non-regular file");
}

type CliOptions = { input?: string; output?: string; check: boolean };

export async function runRustContractsCli(args: string[]) {
  const options: CliOptions = { check: false };
  const flags = new Set<string>();

  for (let index = 0; index < args.length; index++) {
    const flag = args[index]!;

    if (flags.has(flag)) fail("arguments", `duplicate flag ${flag}`);
    flags.add(flag);

    if (flag === "--check") options.check = true;
    else if (flag === "--input" || flag === "--output") {
      const value = args[++index];

      if (!value || value.startsWith("--")) fail("arguments", `${flag} needs a path`);

      if (flag === "--input") options.input = value;
      else options.output = value;
    } else
      fail(
        "arguments",
        `unsupported flag ${flag}; use --input MANIFEST.json --output DIRECTORY [--check]`,
      );
  }

  const { input, output, check } = cliParser.parse(options);
  const inputPath = await realpath(resolve(input));
  const outputPath = resolve(output);

  const artifacts = generateRustContracts(
    parseRustContractManifest(await readFile(inputPath, "utf8")),
  );

  for (const name of Object.keys(artifacts)) {
    const target = join(outputPath, name);
    await assertRegularFile(target);

    if (
      resolve(target) === inputPath ||
      (await realpath(target).catch(() => undefined)) === inputPath
    )
      fail(target, "output must not overwrite the manifest");
  }

  if (check) {
    const stale: string[] = [];

    for (const [name, content] of Object.entries(artifacts)) {
      const target = join(outputPath, name);

      const current = await readFile(target, "utf8").catch((cause: NodeJS.ErrnoException) => {
        if (cause.code === "ENOENT") return undefined;
        throw cause;
      });

      if (current !== content) stale.push(target);
    }

    if (stale.length)
      fail("generated Rust contracts", `stale or missing artifacts:\n${stale.join("\n")}`);

    return;
  }

  await mkdir(outputPath, { recursive: true });

  for (const [name, content] of Object.entries(artifacts)) {
    const target = join(outputPath, name);
    // Exclusive temporary creation plus rename never follows an output-file symlink or leaves a partial artifact.
    const temporary = join(dirname(target), `.${name}.${crypto.randomUUID()}.tmp`);

    try {
      await writeFile(temporary, content, { flag: "wx" });
      await rename(temporary, target);
    } finally {
      await rm(temporary, { force: true });
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await runRustContractsCli(process.argv.slice(2)).catch((cause: Error) => {
    console.error(cause.message);
    process.exitCode = 1;
  });
}
